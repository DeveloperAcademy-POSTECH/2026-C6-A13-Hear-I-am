import Foundation

@main
struct BodyNavigationTests {
    static var count = 0
    static func check(_ condition: @autoclosure () -> Bool, _ message: String) {
        count += 1
        guard condition() else { fatalError("FAIL: \(message)") }
    }
    static func near(_ a: Double, _ b: Double) -> Bool { abs(a - b) < 1e-7 }
    static func main() throws {
        let mapBounds = [MapPoint(-2, 0), MapPoint(4, 0), MapPoint(4, 7), MapPoint(-2, 7)]
        let mapSize = CGSize(width: 360, height: 200)
        let normalMap = PlanTransform(points: mapBounds, size: mapSize)
        let rotatedMap = PlanTransform(points: mapBounds, size: mapSize, rotated180: true)
        let destination = MapPoint(2, 5)
        let normalScreen = normalMap.screen(destination)
        let rotatedScreen = rotatedMap.screen(destination)
        check(near(normalScreen.x + rotatedScreen.x, mapSize.width) && near(normalScreen.y + rotatedScreen.y, mapSize.height), "180 degree map reflects around viewport center")
        for transform in [normalMap, rotatedMap] {
            let selected = transform.stage(transform.screen(destination))
            check(near(selected.x, destination.x) && near(selected.y, destination.y), "map tap preserves physical destination in either orientation")
        }
        check(rotatedMap.screen(MapPoint(0, 0)).y < rotatedMap.screen(MapPoint(0, 1)).y, "audience direction points upward on rotated map")

        let builtIn = GuidanceAudioPort(id: "phone", kind: .speaker)
        let buds = GuidanceAudioPort(id: "buds", kind: .bluetooth)
        check(AudioOutputPolicy.accepts([builtIn], mode: .speaker), "speaker accepted")
        check(AudioOutputPolicy.accepts([buds], mode: .airPods), "Bluetooth accepted regardless of name")
        check(!AudioOutputPolicy.accepts([builtIn], mode: .airPods), "no speaker fallback for AirPods")
        check(!AudioOutputPolicy.accepts([buds], mode: .speaker), "speaker mode excludes Bluetooth")
        check(!AudioOutputPolicy.accepts([], mode: .airPods), "disconnected route rejected")
        check(!AudioOutputPolicy.accepts([GuidanceAudioPort(id: "airplay", kind: .other)], mode: .airPods), "other routes rejected")
        check(!AudioOutputPolicy.accepts([buds, builtIn], mode: .airPods), "mixed output rejected")
        check(AudioOutputPolicy.accepts([buds], mode: .airPods, preparedIDs: ["buds"]), "prepared device stays valid")
        check(!AudioOutputPolicy.accepts([buds], mode: .airPods, preparedIDs: ["other-buds"]), "device replacement requires preparation")

        let p = MapPoint(0, 3)
        let front = BodyNavigationMath.stageHeading(relativeDegrees: 0)
        check(near(front.x, 0) && near(front.y, -1), "calibrated front is audience -Y")
        let right = BodyNavigationMath.stageHeading(relativeDegrees: 90)
        check(near(right.x, -1) && near(right.y, 0), "participant right when facing audience is stage -X")
        let left = BodyNavigationMath.stageHeading(relativeDegrees: -90)
        check(near(left.x, 1) && near(left.y, 0), "participant left is stage +X")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(-2, 3), relativeDegrees: 0)?.kind == .right, "target left on plan is P right")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(2, 3), relativeDegrees: 0)?.kind == .left, "target right on plan is P left")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(0, 1), relativeDegrees: 0)?.kind == .forward, "audience target aligned")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(-2, 3), relativeDegrees: 90)?.kind == .forward, "turning in place aligns target without moving")
        check(near(abs(BodyNavigationMath.instruction(position: p, target: MapPoint(0, 5), relativeDegrees: 0)!.degrees), 180), "behind target is 180 degrees")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(0, 3.2), relativeDegrees: 90)?.kind == .arrived, "arrival independent of facing direction")
        check(BodyNavigationMath.instruction(position: MapPoint(.nan, 0), target: p, relativeDegrees: 0) == nil, "NaN position rejected")
        check(BodyNavigationMath.instruction(position: p, target: p, relativeDegrees: .infinity) == nil, "invalid direction rejected even at D")
        check(BodyNavigationMath.instruction(position: p, target: MapPoint(201, 0), relativeDegrees: 0) == nil, "out-of-bounds packet rejected")
        check(near(BodyNavigationMath.wrap(-358), 2), "baseline wrap crossing positive")
        check(near(BodyNavigationMath.wrap(358), -2), "baseline wrap crossing negative")
        check(BodyNavigationMath.wrap(.nan).isNaN, "invalid heading remains invalid")
        check(near(BodyNavigationMath.outwardHeading(m31: 1, m32: 0, m33: 0)!, 0), "screen outward heading")
        check(near(BodyNavigationMath.outwardHeading(m31: 0, m32: -1, m33: 0)!, 90), "rotation matrix right sign")
        check(near(BodyNavigationMath.outwardHeading(m31: sqrt(0.75), m32: 0, m33: 0.5)!, 0), "lean preserves horizontal heading")
        check(BodyNavigationMath.outwardHeading(m31: 0.1, m32: 0, m33: sqrt(0.99)) == nil, "near-flat posture cannot calibrate")
        check(BodyNavigationMath.outwardHeading(m31: 0, m32: 0, m33: 0) == nil, "zero vector rejected")
        check(BodyNavigationMath.outwardHeading(m31: .nan, m32: 0, m33: 1) == nil, "bad sensor value rejected")
        let square = [MapPoint(-3,0), MapPoint(3,0), MapPoint(3,6), MapPoint(-3,6)]
        check(GuidanceMath.routeInside(p, MapPoint(0,1), polygon: square), "valid interior route")
        check(!GuidanceMath.routeInside(p, MapPoint(3,3), polygon: square), "boundary destination rejected")
        check(!GuidanceMath.routeInside(MapPoint(4,3), p, polygon: square), "outside P rejected")
        let concave = [MapPoint(0,0), MapPoint(4,0), MapPoint(4,4), MapPoint(3,4), MapPoint(3,1), MapPoint(1,1), MapPoint(1,4), MapPoint(0,4)]
        check(!GuidanceMath.routeInside(MapPoint(0.5,3), MapPoint(3.5,3), polygon: concave), "concave exterior shortcut rejected")
        var clock = ReplyClock()
        let a = UUID(), b = UUID(), c = UUID()
        clock.issue(a, at: 100); clock.issue(b, at: 100.1)
        check(clock.accept(b, at: 100.2) == 100.1, "fresh reply yields local request timestamp")
        check(clock.accept(a, at: 100.25) == nil, "out-of-order reply discarded")
        check(clock.accept(b, at: 100.3) == nil, "duplicate reply discarded")
        clock.issue(c, at: 100.3)
        check(clock.accept(c, at: 100.81) == nil, "late network response cannot refresh position")
        check(clock.accept(UUID(), at: 100.9) == nil, "unsolicited reply discarded")
        check(near(ReplyClock.positionDeadline(sent: 100, age: 0.2)!, 100.3), "sensor age subtracted from network budget")
        check(ReplyClock.positionDeadline(sent: 100, age: 0.6) == nil, "old operator observation never playable")
        check(ReplyClock.positionDeadline(sent: 100, age: -.infinity) == nil, "invalid observation age rejected")
        check(ReplyClock.positionDeadline(sent: 100, age: -0.1) == nil, "negative observation age rejected")
        var gate = ArrivalGate()
        check(!gate.update(inside: true, now: 1), "single in-radius sample not arrival")
        check(!gate.update(inside: true, now: 1.4), "dwell less than 0.6 not arrival")
        check(!gate.update(inside: false, now: 1.5), "leaving radius resets dwell")
        check(!gate.update(inside: true, now: 2), "re-entry restarts timer")
        check(gate.update(inside: true, now: 2.7), "continuous dwell confirms arrival")
        check(gate.update(inside: false, now: 3), "arrival stays latched")
        var ledger = RunLedger()
        let stopped = UUID(), completed = UUID(), next = UUID()
        check(ledger.accept(revision: 10), "new revision accepted")
        check(!ledger.accept(revision: 9), "older command state rejected despite newer poll")
        check(ledger.accept(revision: 10), "same revision pose refresh accepted")
        ledger.retire(stopped); ledger.retire(completed)
        check(!ledger.permits(stopped) && !ledger.permits(completed), "stopped and arrived runs never restart")
        check(ledger.permits(next), "explicit new run can start")
        let poll = WearerPoll(calibratedReference: UUID(), relativeDegrees: -30, speakerReady: true, bodyReady: true)
        let encoded = try JSONEncoder().encode(PeerMessage.poll(poll))
        if case .poll(let decoded) = try JSONDecoder().decode(PeerMessage.self, from: encoded) {
            check(decoded.id == poll.id && decoded.relativeDegrees == -30 && decoded.bodyReady, "peer request roundtrip")
        } else { fatalError("wrong packet type") }
        let reply = StageReply(pollID: poll.id, revision: 3, routeID: UUID(), referenceID: poll.calibratedReference,
                               runID: UUID(), polygon: square, start: p, position: p, target: MapPoint(0,1), positionAge: 0.1, message: "안내")
        if case .stage(let decoded) = try JSONDecoder().decode(PeerMessage.self, from: JSONEncoder().encode(PeerMessage.stage(reply))) {
            check(decoded.polygon == square && decoded.revision == 3 && decoded.runID == reply.runID, "stage packet roundtrip")
        } else { fatalError("wrong stage packet") }
        check(BodyInstruction(kind: .left, degrees: -44, distance: 2).spoken == "왼쪽으로 45도 돌아주세요", "speech rounds useful angle")
        check(BodyInstruction(kind: .forward, degrees: 0, distance: 1.24).spoken.contains("1.2"), "distance speech is concise")
        var tracked = GuidanceState(polygon: square)
        tracked.receive([GuidePerson(id: 7, point: p)], time: 10)
        tracked.select(7, time: 10)
        check(tracked.position == p && tracked.selectedID == 7, "operator selects current single P")
        tracked.receive([], time: 10.2, visualContact: true)
        check(tracked.position == p && tracked.lastObservation == 10, "brief visible depth miss does not refresh timestamp")
        tracked.expire(time: 10.51)
        check(tracked.position == nil && tracked.selectedID == 7, "expired position hidden while selection retained")
        tracked.receive([GuidePerson(id: 99, point: MapPoint(0,2))], time: 10.6)
        check(tracked.position == MapPoint(0,2) && tracked.selectedID == 7, "reacquired sole P keeps identity latch")
        tracked.receive([GuidePerson(id: 99, point: p)], time: 10.1)
        check(tracked.position == MapPoint(0,2), "older tracking frame cannot replace newer position")
        tracked.receive([], time: 10.7, visualContact: false)
        check(tracked.position == nil, "visual loss immediately clears P position")
        tracked.invalidate("session reset")
        check(tracked.selectedID == nil && tracked.position == nil, "AR reset removes selection and location")
        tracked.receive([GuidePerson(id: 1, point: MapPoint(.nan, 2))], time: 20)
        check(tracked.people.isEmpty, "invalid measured coordinate cannot reach network")
        check(DirectionSpeechStyle.hour(degrees: 30) == 1, "right 30 is one o'clock")
        check(DirectionSpeechStyle.hour(degrees: 120) == 4, "right 120 is four o'clock")
        check(DirectionSpeechStyle.hour(degrees: -30) == 11, "left 30 is eleven o'clock")
        check(DirectionSpeechStyle.hour(degrees: -120) == 8, "left 120 is eight o'clock")
        check(DirectionSpeechStyle.hour(degrees: 180) == 6 && DirectionSpeechStyle.hour(degrees: -180) == 6, "both rear signs are six o'clock")
        check(DirectionSpeechStyle.hour(degrees: 359) == 12, "clock wrap")
        check(BodyInstruction(kind: .right, degrees: 120, distance: 3).spoken(style: .clock) == "4시 방향으로 돌아주세요", "clock speech")
        check(BodyInstruction(kind: .left, degrees: -13, distance: 3).spoken(style: .clock).contains("왼쪽"), "near noon rounding retains correction side")
        check(BodyInstruction(kind: .arrived, degrees: 0, distance: 0).spoken(style: .clock).contains("멈추세요"), "clock retains arrival stop")
        var candidate = GuidanceState(polygon: square)
        candidate.receive([], time: 30, visualContact: true)
        check(candidate.candidateAvailable && candidate.position == nil, "visual person without depth is selectable but not a position")
        candidate.expire(time: 30.8)
        check(candidate.candidateAvailable, "brief visual gap retains candidate")
        candidate.select(1, time: 30.8)
        check(candidate.selectedID == 1 && candidate.position == nil, "selecting visual candidate cannot invent S position")
        candidate.clearSelection(); candidate.expire(time: 31.1)
        check(!candidate.candidateAvailable, "candidate expires after one second")
        candidate.select(1, time: 31.1)
        check(candidate.selectedID == nil, "expired visual candidate cannot be selected")
        let shoulders = [PoseAnchor(name: "leftShoulder", point: SIMD2<Float>(0.4,0.6), confidence: 0.35),
                         PoseAnchor(name: "rightShoulder", point: SIMD2<Float>(0.6,0.6), confidence: 0.35)]
        check(SinglePersonMath.torsoSamples(shoulders, selected: false).count == 1, "initial paired shoulders now accepted at 0.35")
        check(SinglePersonMath.torsoSamples(Array(shoulders.prefix(1)), selected: false).isEmpty, "initial lone joint still rejected")
        check(SinglePersonMath.acceptsDepthConfidence(1, selected: false), "initial medium depth accepted")
        check(!SinglePersonMath.acceptsDepthConfidence(0, selected: false), "low depth still rejected")
        let segments = StageOverlayMath.grid(concave)
        check(!segments.isEmpty, "concave grid generated")
        check(segments.allSatisfy { a,b in
            (1..<20).allSatisfy { StageGeometry.contains(a + (b-a) * (Double($0)/20), polygon: concave) }
        }, "grid segments stay inside concave stage")
        check(StageOverlayMath.grid([], spacing: 0.5).isEmpty && StageOverlayMath.grid(square, spacing: 0).isEmpty, "invalid grid rejected")
        let narrow = [MapPoint(0.1,0.1),MapPoint(0.3,0.1),MapPoint(0.3,0.3),MapPoint(0.1,0.3)]
        check(StageOverlayMath.grid(narrow).isEmpty, "polygon between grid lines does not form inverted range")
        print("PoC3 body navigation: \(count) checks passed")
    }
}
